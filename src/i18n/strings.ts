export const STRINGS: Record<'tr' | 'en', Record<StringKey, string>> = { tr, en };

export function translate(lang: 'tr' | 'en', key: StringKey, vars?: Record<string, string | number>): string {
  let s = STRINGS[lang][key] ?? STRINGS.tr[key];
  if (vars) for (const k of Object.keys(vars)) s = s.split(`{${k}}`).join(String(vars[k]));
  return s;
}
